#!/usr/bin/env node
/**
 * build-demo-css.cjs
 * Генерирует src/styles/demo-scoped.generated.css: содержимое
 * docs-sections.css, обёрнутое в @scope(.demo-ce) — для страницы /demo,
 * чтобы стили демо-секций не протекали в хром страницы.
 * Заменяет бывший lib-docs-demo-scoped.css (клон lib-docs.css на 99%).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'src/styles/docs-sections.css'), 'utf8')
  // @import внутри @scope невалиден — убираем (шрифты грузит docs-shell/страница)
  .split('\n').filter((l) => !/^\s*@import\s/.test(l)).join('\n');

const out =
  '/* AUTO-GENERATED by scripts/build-demo-css.cjs — НЕ редактировать вручную. */\n' +
  '@scope (.demo-ce) {\n' +
  '  *, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0; }\n' +
  src +
  '\n}\n';

fs.writeFileSync(path.join(root, 'src/styles/demo-scoped.generated.css'), out);
console.log('  – demo-scoped.generated.css (' + (out.length / 1024).toFixed(1) + ' KB)');
